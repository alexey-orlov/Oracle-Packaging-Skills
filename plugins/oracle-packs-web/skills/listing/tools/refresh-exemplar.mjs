#!/usr/bin/env node
/**
 * refresh-exemplar.mjs — regenerate the listing exemplar from the live site.
 *
 *   node refresh-exemplar.mjs --site <site root> [--out <file>] [--check]
 *
 * WHY A TOOL. assets/exemplar-product-entry.js is the spec a listing entry is
 * written to: its cells set the altitude, length and phrasing. A hand copy of the
 * site's entry drifted from it (a retired key, a renamed tier, old category ids),
 * and a builder matching it would have written an entry the site's own checker
 * fails. So the exemplar is never edited by hand: this tool takes the
 * entry for the site manifest's `exemplarProduct` from the site's own data files,
 * and --check says when the copy here has fallen behind.
 *
 * WHAT IT WRITES — four blocks, in the order tools/insert-product.mjs reads them:
 *   1  the SITE_CONTENT.products[] entry        (manifest paths.content)
 *   2  its SITE_CONFIG.products switch block    (paths.config)
 *   3  its SITE_DIAGRAMS figure                 (paths.diagrams)
 *   4  its links.json kit-links entry, as a comment (paths.links)
 * Each block is serialized with JSON.stringify. Block 4 keeps only `interactiveDemo`
 * (the walkthrough's canonical path); its five link values are written as "": they are
 * account-bound or the owner's private links. The site's content-case overlay is applied
 * as at load, so strings read as the site renders them. Otherwise nothing is altered. A
 * run whose output matches the file on disk writes nothing.
 *
 * WHAT IT REFUSES TO DO
 *   - write when the output contains a name on the practice deny-list
 *     (shared/tools/denylist.txt), matched as a whole word, case-insensitively.
 *     The refusal names the entry by its line in the list, never in full;
 *   - write when an input is missing: the manifest's exemplarProduct or one of
 *     its four paths, or the product's entry in any of the four files.
 *
 * INPUTS
 *   --site <dir>   the site root, a folder holding site.manifest.json.
 *                  Default: $ORACLE_SITE_ROOT.
 *   --out <file>   default: ../assets/exemplar-product-entry.js, beside this tool.
 *   --check        build the file in memory and compare it with --out; write
 *                  nothing. Everything is compared except the generation date.
 *
 * The site's data files are evaluated in one sandbox ({ window: {} }), as the
 * site's own tools/sync-links.js does: <publishRoot>/assets/brand.js when it
 * exists, then paths.content, its sibling content-case.js when present (the
 * site's sentence-case overlay), paths.config and paths.diagrams. links.json is
 * parsed as JSON.
 *
 * Exit 0 written, current, or --check clean · 1 refused, or --check found drift ·
 * 2 an input missing or not found. Dependency-free: any Node ≥ 14.
 */

"use strict";

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_OUT = resolve(HERE, "..", "assets", "exemplar-product-entry.js");
/* The plugin's synced copy first, then the repo's own when run from a source
   checkout (the same order as denylist-to-json.py). */
const DENYLISTS = [
  resolve(HERE, "..", "..", "..", "shared", "tools", "denylist.txt"),
  resolve(HERE, "..", "..", "..", "..", "..", "shared", "tools", "denylist.txt")
];
/* Every link but the walkthrough's canonical path: account-bound URLs (the artifact,
   the recording) or the owner's private document links, never shipped as constants. */
const BLANKED = ["onePager", "salesDeck", "featureList", "interactiveDemoArtifact", "video"];
/* The one line --check ignores. */
const DATE_RE = /(GENERATED by tools\/refresh-exemplar\.mjs on )\d{4}-\d{2}-\d{2}/;

const ARGV = process.argv.slice(2);
const opt = (n) => { const i = ARGV.indexOf("--" + n); return i !== -1 && i + 1 < ARGV.length ? ARGV[i + 1] : ""; };
const has = (n) => ARGV.indexOf("--" + n) !== -1;
const die = (code, msg) => { console.error("refresh-exemplar: " + msg); process.exit(code); };

if (has("help")) {
  /* The header comment is the help: every line from `/**` to its closing `*\/`. */
  const lines = readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n");
  const end = lines.findIndex((l, i) => i > 1 && /^\s*\*\/\s*$/.test(l));
  console.log(lines.slice(2, end === -1 ? lines.length : end).join("\n").replace(/^ ?\*\/?/gm, ""));
  process.exit(0);
}

/* ------------------------------------------------------------------ inputs */
if (has("site") && !opt("site")) die(2, "--site needs a folder: the site root, which holds site.manifest.json");
if (has("out") && !opt("out")) die(2, "--out needs a file");
const siteArg = opt("site") || process.env.ORACLE_SITE_ROOT || "";
if (!siteArg) die(2, "no site root: pass --site <dir> or set ORACLE_SITE_ROOT");
const SITE = resolve(siteArg);
const MANIFEST = join(SITE, "site.manifest.json");
if (!existsSync(MANIFEST)) die(2, "not a site root: " + SITE + " holds no site.manifest.json");
const OUT = resolve(opt("out") || DEFAULT_OUT);
const CHECK = has("check");

let manifest;
try { manifest = JSON.parse(readFileSync(MANIFEST, "utf8")); }
catch (e) { die(2, "site.manifest.json cannot be read: " + e.message); }
if (manifest === null || typeof manifest !== "object") die(2, "site.manifest.json is not a JSON object");
const slug = manifest.exemplarProduct;
const paths = manifest.paths || {};
const round = (manifest.contract || {}).round;
if (typeof slug !== "string" || !slug) die(1, "site.manifest.json names no exemplarProduct");
["content", "config", "diagrams", "links"].forEach((key) => {
  if (typeof paths[key] !== "string" || !paths[key]) die(1, "site.manifest.json has no paths." + key);
});
if (round === undefined || round === null || round === "") die(1, "site.manifest.json has no contract.round");

const onDisk = (rel) => {
  const p = resolve(SITE, rel);
  if (!existsSync(p)) die(2, rel + " (site.manifest.json paths) not found under " + SITE);
  return p;
};
const CONTENT = onDisk(paths.content);
const CONFIG = onDisk(paths.config);
const DIAGRAMS = onDisk(paths.diagrams);
const LINKS = onDisk(paths.links);
const BRAND = join(SITE, paths.publishRoot || "site", "assets", "brand.js");

/* ------------------------------------------------------- the site's entries */
/* The site's sentence-case overlay: index.html loads it right after content.js. */
const CASE = join(dirname(CONTENT), "content-case.js");
const box = { window: {}, console: { log() {}, warn() {}, error() {} } };
vm.createContext(box);
[BRAND, CONTENT, CASE, CONFIG, DIAGRAMS].forEach((file) => {
  if ((file === BRAND || file === CASE) && !existsSync(file)) return;
  const rel = relative(SITE, file);
  try { vm.runInContext(readFileSync(file, "utf8"), box, { filename: rel }); }
  catch (e) { die(1, rel + " does not evaluate: " + e.message); }
});
const W = box.window;
const isMap = (v) => v !== null && typeof v === "object" && !Array.isArray(v);

const products = W.SITE_CONTENT && W.SITE_CONTENT.products;
if (!Array.isArray(products)) die(1, paths.content + " defines no window.SITE_CONTENT.products");
const entry = products.find((p) => p && p.slug === slug);
if (!entry) die(1, 'no products[] entry with slug "' + slug + '" in ' + paths.content);

const configs = W.SITE_CONFIG && W.SITE_CONFIG.products;
const config = isMap(configs) && Object.prototype.hasOwnProperty.call(configs, slug) ? configs[slug] : null;
if (!isMap(config)) die(1, 'no SITE_CONFIG.products["' + slug + '"] switch block in ' + paths.config);

const diagrams = W.SITE_DIAGRAMS;
const diagram = isMap(diagrams) && Object.prototype.hasOwnProperty.call(diagrams, slug) ? diagrams[slug] : null;
if (!isMap(diagram)) die(1, 'no SITE_DIAGRAMS["' + slug + '"] figure in ' + paths.diagrams);

let links;
try { links = JSON.parse(readFileSync(LINKS, "utf8")); }
catch (e) { die(1, paths.links + " is not valid JSON: " + e.message); }
const linkEntry = isMap(links) && isMap(links.products) && Object.prototype.hasOwnProperty.call(links.products, slug)
  ? links.products[slug] : null;
if (!isMap(linkEntry)) die(1, 'no products["' + slug + '"] kit-links entry in ' + paths.links);
BLANKED.forEach((key) => { if (Object.prototype.hasOwnProperty.call(linkEntry, key)) linkEntry[key] = ""; });

/* --------------------------------------------------------------- the file */
const now = new Date();
const DATE = now.getFullYear() + "-" + String(now.getMonth() + 1).padStart(2, "0") + "-" +
  String(now.getDate()).padStart(2, "0");
const RULE = " * =========================================================================";
const key = JSON.stringify(slug);
/* JSON of `value`, every line indented; `lead` goes before the first line. */
const block = (value, indent, lead) => JSON.stringify(value, null, 2).split("\n")
  .map((line, i) => indent + (i === 0 ? lead : "") + line).join("\n");
const banner = (lines) => ["/" + RULE.slice(1)]
  .concat(lines.map((l) => (l ? " * " + l : " *")), [RULE + " */"]).join("\n");

const SEGMENTS = [
  {
    name: "the header",
    text: [
      "/* exemplar-product-entry.js — the worked example a listing entry is calibrated to.",
      " *",
      " * GENERATED by tools/refresh-exemplar.mjs on " + DATE + " from the site manifest's",
      " * exemplarProduct, " + key + ", at contract round " + round + ". Never edit it by hand:",
      " *   node tools/refresh-exemplar.mjs --site <site root>            regenerate",
      " *   node tools/refresh-exemplar.mjs --site <site root> --check    report drift (exit 1)",
      " * --check compares everything except the date above.",
      " *",
      " * WHAT THIS IS",
      " *   One entry of `window.SITE_CONTENT.products[]` exactly as the live site stores it,",
      " *   plus the three things that travel with it: its `window.SITE_CONFIG.products[<slug>]`",
      " *   switch block, its `window.SITE_DIAGRAMS[<slug>]` architecture figure, and its",
      " *   kit-links entry in the site's `links.json`.",
      " *",
      " * HOW TO USE IT",
      " *   This file is the SPEC, not a template to paraphrase. Per the exemplar rule: when you",
      " *   fill a structure that already carries an exemplar, match the exemplar's altitude, length",
      " *   and phrasing — the existing cells are the specification, the source documents are not.",
      " *   Read `../references/listing-schema.md` for the key-by-key contract and the invariants,",
      " *   and `../references/listing-rules.md` for the content and messaging rules each string obeys.",
      " *   Strings read as the site renders them: its content-case overlay is applied here as at",
      " *   load, re-casing the few pre-rebrand capitals. A new entry stores sentence case directly.",
      " *",
      " * WHAT WAS BLANKED",
      " *   Block 4's five link values, always written as \"\": account-bound URLs (the artifact,",
      " *   the recording) or the owner's private document links, never constants here; only",
      " *   `interactiveDemo`, the canonical path, is kept. Nothing else is altered. The tool",
      " *   refuses to write when the text contains a name on the practice",
      " *   deny-list (shared/tools/denylist.txt): a customer appears only as an anonymized",
      " *   descriptor with an industry medallion, which is the required shape.",
      " *",
      " * NOTE ON THE FILE EXTENSION",
      " *   `.js` so an editor highlights it. It is a fragment, not a loadable module: the entry is a",
      " *   single array element, and the four blocks below belong to four different files (block 4,",
      " *   a JSON entry, is shown as a comment). Keys are quoted because each block is serialized as",
      " *   JSON; the site's own files write them bare, and both evaluate the same.",
      " */",
      "",
      ""
    ].join("\n")
  },
  {
    name: "block 1 (the " + paths.content + " entry)",
    value: entry,
    text: banner([
      "1 · window.SITE_CONTENT.products[] — one entry",
      "Insert before the closing `]` of `products: [` in " + paths.content,
      "(tools/insert-product.mjs --entry does the splice)."
    ]) + "\n" + block(entry, "    ", "") + ",\n\n"
  },
  {
    name: "block 2 (the " + paths.config + " switch block)",
    value: config,
    text: banner([
      "2 · window.SITE_CONFIG.products[\"<slug>\"] — the per-slug switch block",
      "Insert into the `products: { … }` map in " + paths.config,
      "(tools/insert-product.mjs --config-entry). " + Object.keys(config).length + " keys at contract round " + round + ",",
      "every one present; an empty string means \"do not render that control\",",
      "and a boolean is a real boolean, never a quoted \"false\". No link to a kit",
      "artifact lives here: those are in links.json (block 4)."
    ]) + "\n" + block(config, "    ", key + ": ") + ",\n\n"
  },
  {
    name: "block 3 (the " + paths.diagrams + " figure)",
    value: diagram,
    text: banner([
      "3 · window.SITE_DIAGRAMS[\"<slug>\"] — the architecture figure",
      "Insert into " + paths.diagrams + ". For a new pack it is generated from the",
      "pack's architecture model by tools/diagram_to_site.py, never written by",
      "hand; it is shown here so the shape is in one place. `layout` is \"flow\"",
      "(sources → an OCI group → a human approval target) or \"hub\" (a platform",
      "hub with items); `target` is always the human gate."
    ]) + "\n" + block(diagram, "  ", key + ": ") + ",\n\n"
  },
  {
    name: "block 4 (the " + paths.links + " entry)",
    value: linkEntry,
    text: banner([
      "4 · links.json products[\"<slug>\"] — the kit-links entry",
      "Written by `tools/insert-product.mjs --links`; shown here so the shape is in",
      "one place. " + paths.links + " sits at the site repo's root, outside the publish",
      "root, and is never published. Each key stays \"\" until its artifact exists;",
      "after a change to either demo key or `video`, run the site manifest's",
      "paths.syncLinks from the site root.",
      ""
    ].concat(block(linkEntry, "  ", key + ": ").replace(/\*\//g, "*\\/").split("\n"))) + "\n"
  }
];
const TEXT = SEGMENTS.map((s) => s.text).join("");

/* --------------------------------------------------------- deny-list gate */
function readDenylist() {
  const file = DENYLISTS.find((p) => existsSync(p));
  if (!file) die(2, "no deny-list found: looked for shared/tools/denylist.txt in the plugin and in the repo");
  const entries = [];
  readFileSync(file, "utf8").split("\n").forEach((line, i) => {
    let text = line.split("#")[0].trim();
    if (text.startsWith("~")) text = text.slice(1).trim();
    if (text) entries.push({ text: text, line: i + 1 });
  });
  if (!entries.length) die(2, file + " holds no entries");
  return entries;
}

/* The first key path in `value` whose key or string value contains `needle`. */
function pathOf(value, needle, at) {
  if (typeof value === "string") return needle.test(value) ? at || "(the value)" : "";
  if (value === null || typeof value !== "object") return "";
  for (const k of Object.keys(value)) {
    const where = Array.isArray(value) ? at + "[" + k + "]" : (at ? at + "." : "") + k;
    if (needle.test(k)) return where;
    const hit = pathOf(value[k], needle, where);
    if (hit) return hit;
  }
  return "";
}

/* A whole-word match, case-insensitive and Unicode-aware, so "Sky" never trips on
   "risky": the boundary rule the practice's lint_artifact.py applies. */
const wordRe = (text) => new RegExp("(?<![\\p{L}\\p{N}])" + text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "(?![\\p{L}\\p{N}])", "iu");
const hit = readDenylist().find((e) => wordRe(e.text).test(TEXT));
if (hit) {
  const needle = wordRe(hit.text);
  const seg = SEGMENTS.find((s) => needle.test(s.text));
  const at = seg && seg.value ? pathOf(seg.value, needle, "") : "";
  die(1, "refused — the output contains the deny-list entry on line " + hit.line + " of denylist.txt (\"" +
    hit.text.charAt(0) + "…\", " + hit.text.length + " characters), in " + (seg ? seg.name : "the file") +
    (at ? " at " + at : "") + ". Nothing written; fix the site's copy, never this file.");
}

/* ----------------------------------------------------------- check / write */
const norm = (t) => t.replace(/\r\n/g, "\n").replace(DATE_RE, "$1<date>");
const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
const same = current !== null && norm(current) === norm(TEXT);
const label = '"' + slug + '" at contract round ' + round;
const RUN = "node " + relative(process.cwd(), fileURLToPath(import.meta.url)) + " --site " + SITE;

if (CHECK) {
  if (same) { console.log("refresh-exemplar: OK — " + OUT + " matches the site's " + label); process.exit(0); }
  if (current === null) die(1, "drift — " + OUT + " does not exist; run: " + RUN);
  /* The first differing line, mapped to the block of the generated file it falls in. */
  const want = norm(TEXT).split("\n");
  const got = norm(current).split("\n");
  let line = 0;
  while (line < want.length && line < got.length && want[line] === got[line]) line++;
  let where = "after block 4 (the file on disk has extra lines)";
  let start = 0;
  for (const s of SEGMENTS) {
    const size = s.text.split("\n").length - 1;
    if (line < start + size) { where = s.name; break; }
    start += size;
  }
  die(1, "drift — " + OUT + " differs from the site's " + label + " first in " + where +
    ", line " + (line + 1) + "; run: " + RUN);
}

if (same) {
  console.log("refresh-exemplar: " + OUT + " already matches the site's " + label + "; nothing written");
  process.exit(0);
}
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, TEXT, "utf8");
console.log("refresh-exemplar: wrote " + OUT + " from the site's " + label +
  " (block 4: " + BLANKED.join(", ") + " blanked)");
